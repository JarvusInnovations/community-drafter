import { chmodSync, readFileSync } from "node:fs";
import { execSync } from "node:child_process";

import * as esbuild from "esbuild";

import { BUNDLE_OUTFILE, ENTRY_POINT } from "./paths.js";

/**
 * Build the self-contained bundle committed at
 * `skills/signatories-axi/scripts/signatories-axi.mjs`. All dependencies
 * (`axi-sdk-js`, `@toon-format/toon`) are inlined so the artifact runs
 * under plain `node` on a machine that only has the skill installed — no
 * `npm install`, no `node_modules` (`axi-skills` § build pipeline).
 */
export interface BuildResult {
  ok: boolean;
  message: string;
}

function gitVersion(): string {
  try {
    return execSync("git describe --tags --always", { encoding: "utf8" }).trim() || "dev";
  } catch {
    return "dev";
  }
}

/**
 * Committing the bundle changes the git sha (and a shallow CI checkout may
 * lack tags), so the embedded `git describe` version always differs
 * between the committed bundle and a fresh build. Strip the version
 * literal out of both sides before comparing, so version drift never
 * trips the gate while any real source change still does.
 */
function normalizeVersion(source: string): string {
  return source.replace(/"[^"]*" : "dev"/, '"__VERSION__" : "dev"');
}

export async function buildCliBundle(check: boolean): Promise<BuildResult> {
  const result = await esbuild.build({
    entryPoints: [ENTRY_POINT],
    outfile: BUNDLE_OUTFILE,
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node20",
    legalComments: "none",
    define: { __SIGNATORIES_AXI_VERSION__: JSON.stringify(gitVersion()) },
    banner: {
      js: "#!/usr/bin/env node\n// GENERATED by scripts/build-cli.ts from packages/cli/src/cli/ — do not edit. Run `bun run build` in packages/cli.",
    },
    write: !check,
  });

  if (!check) {
    chmodSync(BUNDLE_OUTFILE, 0o755);
    return { ok: true, message: `Wrote ${BUNDLE_OUTFILE}` };
  }

  const generated = result.outputFiles![0]!.text;
  let committed: string;
  try {
    committed = readFileSync(BUNDLE_OUTFILE, "utf8");
  } catch {
    return {
      ok: false,
      message: `${BUNDLE_OUTFILE} does not exist — run \`bun run build\` in packages/cli`,
    };
  }

  if (normalizeVersion(generated) !== normalizeVersion(committed)) {
    return {
      ok: false,
      message: `${BUNDLE_OUTFILE} is out of date — run \`bun run build\` in packages/cli and commit the result`,
    };
  }
  return { ok: true, message: `${BUNDLE_OUTFILE} is up to date` };
}
